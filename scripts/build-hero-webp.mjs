/** Derive delivery files from the approved originals. Never redraw or overwrite sources. */
import sharp from "sharp";
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";

const out = "public/delivery";
await mkdir(out, { recursive: true });
for (const file of await readdir(out)) await rm(`${out}/${file}`);
const assets = {};
async function emit(name, bytes) {
    const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
    const path = `/delivery/${name}-${hash}.webp`;
    await writeFile(`public${path}`, bytes);
    assets[name] = path;
    return bytes.length;
}
for (const width of [560, 1120]) {
    await emit(`hero-${width}`, await sharp("public/images/scoracle_crystal_ball.webp")
        .resize({ width }).webp({ quality: 85, alphaQuality: 100, effort: 6 }).toBuffer());
}
for (const [name, source] of [
    ["curtains", "impasto-drapes-threaded-default-4.webp"],
    ["curtains-team", "impasto-drapes-threaded-3.webp"],
]) {
    await emit(name, await sharp(`public/images/${source}`)
        .resize({ width: 1024 }).webp({ quality: 78, effort: 6 }).toBuffer());
}
let before = 0, after = 0;
for (const file of (await readdir("public/deck-art")).filter(f => /^engraving-.*-v1\.webp$/.test(f)).sort()) {
    const source = await readFile(`public/deck-art/${file}`);
    const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    // These are ink masks displayed at 8.5% opacity. Sixteen alpha intervals
    // limit the final pixel change to <1/255, while preserving the full geometry.
    for (let i = 3; i < data.length; i += 4) data[i] = Math.min(255, Math.round(data[i] / 17) * 17);
    const bytes = await sharp(data, { raw: info }).webp({ lossless: true, effort: 6 }).toBuffer();
    after += await emit(file.replace(/-v1\.webp$/, ""), bytes);
    before += source.length;
}
await writeFile("src/lib/delivery-assets.generated.ts",
    `// Generated by scripts/build-hero-webp.mjs from approved source artwork.\nexport const deliveryAssets = ${JSON.stringify(assets, null, 2)} as const;\n`);
await writeFile("src/delivery-assets.generated.css", ":root {\n" + Object.entries(assets)
    .filter(([name]) => name.startsWith("engraving-"))
    .map(([name, path]) => `  --delivery-${name}: url("${path}");`).join("\n") + "\n}\n");
console.log(`Engraving delivery: ${Math.round(before / 1024)} → ${Math.round(after / 1024)} KiB; source artwork unchanged.`);
